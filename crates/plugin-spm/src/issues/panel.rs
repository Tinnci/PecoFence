//! The issue panel: one provider, two widths. A narrow fence is the 我的问题 inbox, a wide one
//! the 问题 workspace. SPM answers every question; this panel only asks, remembers what the user
//! chose, and sends local verdicts back. Nothing here writes to Lark, Meegle, Gerrit or Jenkins.
use super::{ProposalAction, layout, text::Lang};
use crate::board::{
    palette::Palette,
    text::{HostMeasure, Measure},
};
use pecofence_plugin_api::{
    design::{ContentScale, LayoutTracker},
    scene::Scene,
    *,
};
use serde::{Deserialize, Serialize};
use spm_contracts::*;
use std::{
    collections::{BTreeMap, HashMap, HashSet},
    rc::Rc,
    sync::Arc,
    time::{Duration, Instant},
};

pub const PROVIDER_ID: &str = "pecofence.spm.issues";
/// From this logical width on, the panel lays out the three-pane workspace.
pub const WORKSPACE_WIDTH: f32 = 900.0;

#[derive(Clone, Debug, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Config {
    #[serde(default)]
    pub demo: bool,
    #[serde(default = "project")]
    pub project_id: String,
    #[serde(default)]
    pub navigation_origins: crate::navigation::NavigationOrigins,
}
fn project() -> String {
    "orion-ir".into()
}
pub fn demo_config() -> (u16, serde_json::Value) {
    (1, serde_json::json!({"demo": true}))
}
pub fn live_config() -> (u16, serde_json::Value) {
    (1, serde_json::json!({"demo": false}))
}

/// Every Orion answer spmd serves, generated by spmd's `orion_demo_bundle_is_served_and_valid`.
#[derive(Clone, Debug, Deserialize)]
pub struct DemoBundle {
    pub query: QueryIssuesResponse,
    pub details: BTreeMap<String, IssueDetail>,
    pub readiness: GateReadiness,
    pub what_if: GateWhatIf,
    pub search: SearchWorkspaceResponse,
}
pub fn demo_bundle() -> DemoBundle {
    serde_json::from_str(include_str!("../../fixtures/issues-demo.json"))
        .expect("verified deterministic issue fixture")
}

#[derive(Clone, Copy, Debug, Default, PartialEq, Eq)]
pub enum View {
    #[default]
    Issues,
    Search,
}

#[derive(Clone, Debug, PartialEq)]
pub enum Target {
    View(View),
    Queue(Option<IssueQueue>),
    Select(String),
    /// Narrow width: leave the detail for the inbox.
    Back,
    Proposal(String, ProposalAction),
    Suggestion(usize, SuggestionVerdict),
    Find,
    Mode(SearchMode),
    Scope(SearchScope),
}

/// What the panel currently holds. Layout reads it; only `Panel` changes it.
pub struct State {
    pub list: Option<QueryIssuesResponse>,
    pub readiness: Option<GateReadiness>,
    pub what_if: Option<GateWhatIf>,
    pub detail: Option<IssueDetail>,
    pub selected: Option<String>,
    pub queue: Option<IssueQueue>,
    pub view: View,
    pub search: Option<SearchWorkspaceResponse>,
    pub query: String,
    pub mode: SearchMode,
    pub scope: SearchScope,
    /// Narrow width shows one column: the inbox, or the selected issue.
    pub narrow_detail: bool,
    pub notice: Option<String>,
}

impl Default for State {
    fn default() -> Self {
        Self {
            list: None,
            readiness: None,
            what_if: None,
            detail: None,
            selected: None,
            queue: None,
            view: View::Issues,
            search: None,
            // The design's example question, so the search view opens with an answer.
            query: "搜索框 底部".into(),
            mode: SearchMode::Hybrid,
            scope: SearchScope::All,
            narrow_detail: false,
            notice: None,
        }
    }
}

pub struct IssuesPlugin;
impl PanelProvider for IssuesPlugin {
    fn descriptor(&self) -> ProviderDescriptor {
        ProviderDescriptor {
            id: PROVIDER_ID,
            api_major: 1,
            config_major: 1,
            required_services: &["render", "theme", "ipc"],
        }
    }
    fn validate(&self, config: &PanelConfig) -> Result<()> {
        if config.version != 1 {
            return Err(Error::Invalid("unsupported issue config version".into()));
        }
        let parsed: Config =
            serde_json::from_slice(&config.bytes).map_err(|e| Error::Invalid(e.to_string()))?;
        ProjectId::new(&parsed.project_id).map_err(|e| Error::Invalid(e.to_string()))?;
        crate::navigation::validate_origins(&parsed.navigation_origins)
    }
    fn create(&self, ctx: PluginContext, input: CreatePanel) -> Result<Box<dyn PanelInstance>> {
        self.validate(&input.config)?;
        let config = serde_json::from_slice(&input.config.bytes)
            .map_err(|e| Error::Invalid(e.to_string()))?;
        Ok(Box::new(Panel::new(ctx, input.key, config)?))
    }
}

pub struct Panel {
    ctx: PluginContext,
    key: InstanceKey,
    config: Config,
    project: ProjectId,
    demo: Option<DemoBundle>,
    mount: Option<MountKey>,
    pub state: State,
    focus: Option<String>,
    scroll: f32,
    content_height: f32,
    viewport_height: f32,
    field: RectDip,
    palette: Palette,
    locale: &'static str,
    actions: Vec<(String, Target, RectDip)>,
    ids: HashMap<String, u64>,
    next_id: u64,
    tracker: LayoutTracker,
    layout_revision: u64,
    view_revision: u64,
    prepared_view: u64,
    frame_revision: u64,
    published_chrome: bool,
    chrome_warmup_until: Instant,
    pending: HashSet<Token>,
    last_refresh: Instant,
    stopped: bool,
}

const REFRESH: Duration = Duration::from_secs(120);

impl Panel {
    pub fn new(ctx: PluginContext, key: InstanceKey, config: Config) -> Result<Self> {
        let theme = ctx
            .theme
            .with(|t| t.snapshot())
            .unwrap_or_else(|_| Arc::new(ThemeSnapshot::dark()));
        let project =
            ProjectId::new(&config.project_id).map_err(|e| Error::Invalid(e.to_string()))?;
        let demo = config.demo.then(demo_bundle);
        let mut panel = Self {
            ctx,
            key,
            project,
            demo,
            config,
            mount: None,
            state: State::default(),
            focus: None,
            scroll: 0.0,
            content_height: 0.0,
            viewport_height: 780.0,
            field: RectDip::default(),
            palette: Palette::from_theme(&theme),
            locale: "zh-CN",
            actions: vec![],
            ids: HashMap::new(),
            next_id: 2,
            tracker: LayoutTracker::default(),
            layout_revision: 0,
            view_revision: 1,
            prepared_view: 0,
            frame_revision: 0,
            published_chrome: false,
            chrome_warmup_until: Instant::now() + Duration::from_secs(3),
            pending: HashSet::new(),
            last_refresh: Instant::now(),
            stopped: false,
        };
        if let Some(demo) = &panel.demo {
            panel.state.list = Some(demo.query.clone());
            panel.state.readiness = Some(demo.readiness.clone());
            panel.state.what_if = Some(demo.what_if.clone());
        }
        // Open on the issue that needs the user first, as the designs do.
        panel.select(first_needing_me(panel.state.list.as_ref()))?;
        panel.load()?;
        Ok(panel)
    }
    fn lang(&self) -> Lang {
        Lang::new(self.locale)
    }
    fn changed(&mut self) {
        self.view_revision += 1;
    }
    fn send(&mut self, request: Request) -> Result<()> {
        let bytes = crate::encode_request(&request)?;
        match self.ctx.ipc.with(|ipc| ipc.send(&self.ctx.scope, bytes)) {
            Ok(token) => {
                self.pending.insert(token);
            }
            Err(_) => self.state.notice = Some(self.lang().t("Refresh failed").into()),
        }
        Ok(())
    }
    /// Live: ask for the list and the gate. The what-if follows once the gate is known.
    fn load(&mut self) -> Result<()> {
        if self.demo.is_none() {
            self.send(Request::QueryIssues(QueryIssuesRequest {
                project_id: self.project.clone(),
                queue: None,
                kind: None,
                limit: 50,
            }))?;
            self.send(Request::GetGateReadiness(GetGateReadinessRequest {
                project_id: self.project.clone(),
            }))?;
        }
        self.last_refresh = Instant::now();
        Ok(())
    }
    fn select(&mut self, id: Option<String>) -> Result<()> {
        self.state.selected = id.clone();
        self.state.detail = None;
        let Some(id) = id else { return Ok(()) };
        match &self.demo {
            Some(demo) => self.state.detail = demo.details.get(&id).cloned(),
            None => self.send(Request::GetIssue(GetIssueRequest {
                project_id: self.project.clone(),
                id,
            }))?,
        }
        Ok(())
    }
    fn review(&mut self, proposal_id: &str, action: ProposalAction) -> Result<()> {
        let lang = self.lang();
        let Some(proposal) = self
            .state
            .detail
            .as_ref()
            .and_then(|d| d.proposals.iter().find(|p| p.id == proposal_id))
            .cloned()
        else {
            return Ok(());
        };
        let Some(request) = super::review_request(&self.project, &proposal, action) else {
            // Reply in Lark opens the conversation; without a Lark origin there is nowhere to go.
            self.state.notice = Some(lang.t("Lark is not configured as a source").into());
            return Ok(());
        };
        self.state.notice = (action == ProposalAction::ConfirmMeegle)
            .then(|| super::confirmation_note(lang, false).map(str::to_string))
            .flatten();
        match &self.demo {
            Some(demo) => {
                let at = demo.query.observed_through.unwrap_or_else(chrono::Utc::now);
                if let Some(detail) = &mut self.state.detail {
                    apply_review(detail, &request, at);
                }
            }
            None => self.send(Request::ReviewAssignment(request))?,
        }
        Ok(())
    }
    fn judge(&mut self, index: usize, verdict: SuggestionVerdict) -> Result<()> {
        let Some(detail) = &mut self.state.detail else {
            return Ok(());
        };
        let Some(suggestion) = detail.suggestions.get(index).cloned() else {
            return Ok(());
        };
        // Rule suggestions carry no object key; they are shown, never judged.
        let Some(object_key) = suggestion.object_key.clone() else {
            return Ok(());
        };
        if self.demo.is_some() {
            detail.suggestions.remove(index);
            if verdict == SuggestionVerdict::Dismiss {
                detail.suggestions_dismissed += 1;
            }
            return Ok(());
        }
        self.send(Request::JudgeSuggestion(JudgeSuggestionRequest {
            project_id: self.project.clone(),
            kind: suggestion.kind,
            subject_key: suggestion.subject_key,
            object_key,
            verdict,
            note: None,
        }))
    }
    fn search(&mut self) -> Result<()> {
        if self.state.query.trim().is_empty() {
            self.state.search = None;
            return Ok(());
        }
        match &self.demo {
            Some(demo) => {
                let mut found = demo.search.clone();
                found.mode_requested = self.state.mode;
                found
                    .results
                    .retain(|r| scope_admits(self.state.scope, r.kind));
                self.state.search = Some(found);
            }
            None => self.send(Request::SearchWorkspace(SearchWorkspaceRequest {
                project_id: self.project.clone(),
                query: self.state.query.clone(),
                mode: self.state.mode,
                scope: self.state.scope,
                limit: 20,
            }))?,
        }
        Ok(())
    }
    fn invoke(&mut self, target: Target) -> Result<PanelUpdate> {
        match target {
            Target::View(view) => {
                self.state.view = view;
                self.scroll = 0.0;
                if view == View::Search && self.state.search.is_none() {
                    self.search()?;
                }
            }
            Target::Queue(queue) => {
                self.state.queue = if self.state.queue == queue {
                    None
                } else {
                    queue
                };
                self.scroll = 0.0;
            }
            Target::Select(id) => {
                self.state.view = View::Issues;
                self.state.narrow_detail = true;
                self.state.notice = None;
                self.scroll = 0.0;
                self.select(Some(id))?;
            }
            Target::Back => {
                self.state.narrow_detail = false;
                self.scroll = 0.0;
            }
            Target::Proposal(id, action) => self.review(&id, action)?,
            Target::Suggestion(i, verdict) => self.judge(i, verdict)?,
            Target::Find => {
                let mut style =
                    TextInputStyle::new(self.field, self.palette.primary, self.palette.card, 13.0);
                style.accent = Some(self.palette.accent);
                style.placeholder = Some(self.lang().t("Search issues, messages or people"));
                return Ok(PanelUpdate {
                    commands: vec![HostCommand::RequestTextInput {
                        action: 4,
                        initial: self.state.query.clone(),
                        multiline: false,
                        style: Some(style),
                    }],
                    relayout: false,
                });
            }
            Target::Mode(mode) => {
                self.state.mode = mode;
                self.search()?;
            }
            Target::Scope(scope) => {
                self.state.scope = scope;
                self.search()?;
            }
        }
        self.changed();
        Ok(self.update())
    }
    fn update(&mut self) -> PanelUpdate {
        self.published_chrome = true;
        PanelUpdate {
            commands: vec![
                HostCommand::Invalidate,
                HostCommand::SetChrome(self.chrome()),
            ],
            relayout: true,
        }
    }
    pub fn chrome(&self) -> PanelChrome {
        let lang = self.lang();
        let status = if let Some(text) = &self.state.notice {
            Some(ChromeStatus {
                text: text.clone(),
                severity: ChromeSeverity::Warning,
            })
        } else {
            self.state
                .readiness
                .as_ref()
                .filter(|r| !r.ready)
                .map(|r| ChromeStatus {
                    text: format!(
                        "× {} {}",
                        super::gate_name(r.next_gate),
                        lang.t("Not ready")
                    ),
                    severity: ChromeSeverity::Error,
                })
        };
        let subtitle = match &self.state.readiness {
            Some(r) => format!(
                "{} · DI {}{}",
                self.config.project_id,
                super::number(r.di.value),
                if self.demo.is_some() {
                    format!(" · {}", lang.t("Demo data"))
                } else {
                    String::new()
                }
            ),
            None => lang.t("Loading issues…").into(),
        };
        PanelChrome {
            title: lang.t("Issues").into(),
            subtitle,
            status,
            commands: vec![
                ChromeCommand {
                    id: 1,
                    label: lang.t("Refresh").into(),
                    glyph: '\u{E72C}',
                    enabled: self.pending.is_empty(),
                },
                ChromeCommand {
                    id: 2,
                    label: lang.t("Search").into(),
                    glyph: '\u{E721}',
                    enabled: true,
                },
            ],
            surface: self.palette.ground,
        }
    }
    fn completion(&mut self, bytes: &[u8]) -> Result<()> {
        let invalid = |e: ContractError| Error::Invalid(e.to_string());
        match crate::decode_event(bytes)?.body {
            Body::Response(Response::QueryIssues(list)) => {
                list.validate().map_err(invalid)?;
                let first = self
                    .state
                    .selected
                    .is_none()
                    .then(|| first_needing_me(Some(&list)))
                    .flatten();
                self.state.list = Some(list);
                if first.is_some() {
                    self.select(first)?;
                }
            }
            Body::Response(Response::GetGateReadiness(readiness)) => {
                readiness.validate().map_err(invalid)?;
                self.send(Request::GateWhatIf(GateWhatIfRequest {
                    project_id: self.project.clone(),
                    gate: readiness.next_gate,
                    max_steps: 8,
                }))?;
                self.state.readiness = Some(readiness);
            }
            Body::Response(Response::GateWhatIf(what_if)) => {
                what_if.validate().map_err(invalid)?;
                self.state.what_if = Some(what_if);
            }
            Body::Response(Response::GetIssue(detail)) => {
                detail.validate().map_err(invalid)?;
                if self.state.selected.as_deref() == Some(detail.item.id.as_str()) {
                    self.state.detail = Some(detail);
                }
            }
            // A verdict or judgment changes what the issue shows: read it again.
            Body::Response(Response::ReviewAssignment(_) | Response::JudgeSuggestion(_)) => {
                self.select(self.state.selected.clone())?;
            }
            Body::Response(Response::SearchWorkspace(found)) => {
                found.validate().map_err(invalid)?;
                self.state.search = Some(found);
            }
            Body::Response(Response::RefreshIssues(_)) => {
                self.load()?;
                self.select(self.state.selected.clone())?;
            }
            Body::Error(_) => self.state.notice = Some(self.lang().t("Refresh failed").into()),
            _ => {}
        }
        Ok(())
    }
    pub fn handle(&mut self, event: PanelEvent) -> Result<PanelUpdate> {
        if self.stopped {
            return Err(Error::Closed);
        }
        match event {
            PanelEvent::Command { id: 1 } => {
                self.state.notice = None;
                // The only issue request that writes, and only to the local people database.
                if self.demo.is_none() && self.pending.is_empty() {
                    self.send(Request::RefreshIssues(RefreshIssuesRequest {
                        project_id: self.project.clone(),
                    }))?;
                }
                self.last_refresh = Instant::now();
                self.changed();
            }
            PanelEvent::Command { id: 2 } => {
                return self.invoke(Target::View(if self.state.view == View::Search {
                    View::Issues
                } else {
                    View::Search
                }));
            }
            PanelEvent::Wake => {
                if self.demo.is_none() && self.last_refresh.elapsed() >= REFRESH {
                    self.load()?;
                    self.changed();
                }
            }
            PanelEvent::Invoke {
                action,
                layout_revision,
            } => {
                if layout_revision == self.layout_revision
                    && self.prepared_view == self.view_revision
                    && let Some((key, target, _)) = action
                        .checked_sub(16)
                        .and_then(|i| self.actions.get(i as usize))
                        .cloned()
                {
                    self.focus = Some(key);
                    return self.invoke(target);
                }
            }
            PanelEvent::Completion { operation, result } => {
                if self.pending.remove(&operation) {
                    if result.and_then(|bytes| self.completion(&bytes)).is_err() {
                        self.state.notice = Some(self.lang().t("Refresh failed").into());
                    }
                    self.changed();
                }
            }
            PanelEvent::TextSubmitted { action: 4, text } => {
                self.state.query = text.trim().into();
                self.state.view = View::Search;
                self.scroll = 0.0;
                self.search()?;
                self.changed();
            }
            PanelEvent::Key { key, .. } => {
                match key {
                    PanelKey::Escape => {
                        if self.state.view == View::Search {
                            self.state.view = View::Issues;
                        } else {
                            self.state.narrow_detail = false;
                        }
                        self.focus = None;
                        self.scroll = 0.0;
                    }
                    PanelKey::Refresh => return self.handle(PanelEvent::Command { id: 1 }),
                    PanelKey::Enter => {
                        if let Some((_, target, _)) = self
                            .actions
                            .iter()
                            .find(|(k, _, _)| Some(k) == self.focus.as_ref())
                            .cloned()
                        {
                            return self.invoke(target);
                        }
                    }
                    PanelKey::Up | PanelKey::Down | PanelKey::Left | PanelKey::Right => {
                        let forward = matches!(key, PanelKey::Down | PanelKey::Right);
                        let index = self
                            .actions
                            .iter()
                            .position(|(k, _, _)| Some(k) == self.focus.as_ref());
                        let next = match index {
                            None => 0,
                            Some(i) if forward => (i + 1).min(self.actions.len().saturating_sub(1)),
                            Some(i) => i.saturating_sub(1),
                        };
                        self.focus = self.actions.get(next).map(|(k, _, _)| k.clone());
                    }
                    PanelKey::PageDown => self.scroll_by(self.viewport_height * 0.6),
                    PanelKey::PageUp => self.scroll_by(-self.viewport_height * 0.6),
                    PanelKey::Home => self.scroll = 0.0,
                    PanelKey::End => self.scroll_by(f32::MAX / 4.0),
                }
                self.changed();
            }
            PanelEvent::Scroll { lines, .. } => {
                self.scroll_by(lines * 36.0);
                self.changed();
            }
            PanelEvent::ThemeChanged { .. } => {
                if let Ok(theme) = self.ctx.theme.with(|t| t.snapshot()) {
                    self.palette = Palette::from_theme(&theme);
                }
                self.changed();
            }
            _ => {}
        }
        Ok(self.update())
    }
    fn scroll_by(&mut self, delta: f32) {
        let max = (self.content_height - self.viewport_height + 40.0).max(0.0);
        self.scroll = (self.scroll + delta).clamp(0.0, max);
    }
    pub fn prepare(&mut self, input: FrameInput, measure: &dyn Measure) -> Result<Scene> {
        let mount_key = self.mount.ok_or(Error::Closed)?;
        self.locale = input.locale;
        self.frame_revision += 1;
        let scale = ContentScale::new(input.viewport, input.text_scale);
        let viewport = scale.logical_viewport();
        self.viewport_height = viewport.h;
        let mut built = layout::build(
            &self.state,
            self.focus.as_deref(),
            self.scroll,
            self.lang(),
            viewport,
            &self.palette,
            measure,
            &mut self.ids,
            &mut self.next_id,
        );
        self.content_height = built.content_height;
        self.field = scale.rect(built.field);
        self.actions = built.actions;
        for node in &mut built.nodes {
            node.rect = scale.rect(node.rect);
            node.style.size *= scale.factor();
            node.style.radius *= scale.factor();
        }
        let scene = Scene::new(
            FrameIdentity {
                mount_key,
                frame_revision: self.frame_revision,
                layout_revision: self.layout_revision,
                theme_epoch: input.theme_epoch,
                device_epoch: input.device_epoch,
            },
            input.viewport,
            built.nodes,
        )?;
        self.layout_revision = self.tracker.update(scene.hit_tree(), self.view_revision)?;
        self.prepared_view = self.view_revision;
        Ok(scene.with_layout_revision(self.layout_revision))
    }
}

/// The issue the user should look at first: one that needs their reply, else the first listed.
fn first_needing_me(list: Option<&QueryIssuesResponse>) -> Option<String> {
    let items = &list?.items;
    items
        .iter()
        .find(|i| {
            i.queues.contains(&IssueQueue::NeedsMyReply)
                && i.queues
                    .contains(&IssueQueue::AwaitingAssignmentConfirmation)
        })
        .or_else(|| {
            items
                .iter()
                .find(|i| i.queues.contains(&IssueQueue::NeedsMyReply))
        })
        .or(items.first())
        .map(|i| i.id.clone())
}

fn scope_admits(scope: SearchScope, kind: SearchKind) -> bool {
    match scope {
        SearchScope::All => true,
        SearchScope::Issues => kind == SearchKind::Issue,
        SearchScope::Messages => kind == SearchKind::Message,
        SearchScope::People => kind == SearchKind::Person,
        SearchScope::Changes => kind == SearchKind::Change,
    }
}

/// Demo stand-in for spmd's review: the verdict moves the proposal, rejected ones are counted.
pub fn apply_review(
    detail: &mut IssueDetail,
    request: &ReviewAssignmentRequest,
    at: chrono::DateTime<chrono::Utc>,
) {
    let Some(index) = detail
        .proposals
        .iter()
        .position(|p| p.id == request.proposal_id)
    else {
        return;
    };
    match request.verdict {
        AssignmentVerdict::Reject => {
            detail.proposals.remove(index);
            detail.proposals_rejected += 1;
        }
        verdict => {
            let proposal = &mut detail.proposals[index];
            proposal.status = if verdict == AssignmentVerdict::LocalOnly {
                ProposalStatus::LocalOnly
            } else {
                ProposalStatus::Confirmed
            };
            proposal.reviewed_at = Some(at);
        }
    }
}

impl PanelInstance for Panel {
    fn mount(&mut self, ctx: MountContext) -> Result<()> {
        if ctx.key.instance != self.key {
            return Err(Error::Invalid("wrong issue instance".into()));
        }
        self.mount = Some(ctx.key);
        Ok(())
    }
    fn event(&mut self, event: PanelEvent) -> Result<PanelUpdate> {
        self.handle(event)
    }
    fn prepare_frame(&mut self, input: FrameInput) -> Result<Rc<dyn PreparedFrame>> {
        let render = self.ctx.render.clone();
        let measure = move |spec: &TextSpec, width: f32| {
            render
                .with(|r| r.measure(spec, width))
                .ok()
                .map(|m| (m.width, m.height))
        };
        Ok(Rc::new(self.prepare(input, &HostMeasure(&measure))?))
    }
    fn unmount(&mut self, key: MountKey) {
        if self.mount == Some(key) {
            self.mount = None;
        }
    }
    fn begin_stop(&mut self, _: StopReason) {
        self.stopped = true;
        for token in self.pending.drain() {
            let _ = self.ctx.ipc.with(|ipc| ipc.cancel(token));
        }
    }
    fn next_wake_after(&self) -> Option<Duration> {
        // Publish the chrome again after the fence HWND exists, as the CI panel does.
        if !self.stopped && Instant::now() < self.chrome_warmup_until {
            return Some(Duration::from_millis(500));
        }
        if !self.published_chrome && !self.stopped {
            return Some(Duration::from_millis(10));
        }
        (self.demo.is_none() && !self.stopped).then(|| {
            REFRESH
                .saturating_sub(self.last_refresh.elapsed())
                .max(Duration::from_secs(1))
        })
    }
}

