def lane_counts(cards: list[dict]) -> list[dict]:
    lanes = []
    for lane in LANES:
        counts = {"todo": 0, "doing": 0, "done": 0, "unclassified": 0, "blocked": 0}
        for c in cards:
            if c["swimlane"] == lane:
                counts[c["column"]] += 1
                counts["blocked"] += "blocked" in c["stage"]["overlays"]
        lanes.append({"swimlane": lane, "counts": counts})
    return lanes


