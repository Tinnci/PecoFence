def card_evidence(board: dict) -> list[dict]:
    responses = []
    for c in board["cards"]:
        ids = {e for r in c["relationships"] for e in r["evidence"]}
        ids |= {e for b in c["blockers"] for e in b["evidence"]}
        ids |= {m["evidence_id"] for m in c["event_marks"]}
        if c["business_number"] == "ORION-R-102":
            ids |= {"ev:l-request", "ev:l-reply"}
        items = []
        for eid in ids:
            source, locator, at, seen, summary = EVIDENCE[eid]
            if at > board["computed_at"]:
                continue
            items.append({
                "id": eid, "source": source, "field_locator": locator, "source_time": at,
                "observed_at": seen, "summary": summary,
                "relationship_ids": sorted(r["id"] for r in c["relationships"] if eid in r["evidence"]),
            })
        items.sort(key=lambda item: (item["source_time"], item["id"]))
        responses.append({"card_id": c["card_id"], "revision": board["revision"], "items": items,
                          "next_cursor": None})
    return responses


def build() -> dict:
    values = {}
    for step in range(len(STEPS)):
        board = snapshot(step)
        values[f"step{step + 1}-board.json"] = board
        values[f"step{step + 1}-evidence.json"] = card_evidence(board)
    return values
