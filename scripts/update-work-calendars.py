"""Refresh public snapshots. CN: published arrangements; IN/BD/BR: versioned holiday rules.
Add countries to REGIONS; all upstream-supported subdivisions are included automatically.
"""
import sys
import json
from pathlib import Path
from urllib.request import urlopen
import holidays

ROOT = Path(__file__).resolve().parents[1] / "crates/work-calendar"
REGIONS = {"IN": "Asia/Kolkata", "BD": "Asia/Dhaka", "BR": "America/Sao_Paulo"}
YEARS = range(2025, 2028)
entries = []
for year in YEARS:
    url = f"https://raw.githubusercontent.com/NateScarlet/holiday-cn/master/{year}.json"
    if "--cached-china" in sys.argv:
        raw = (ROOT / f"data/china/{year}.json").read_bytes()
    else:
        with urlopen(url, timeout=20) as response:
            raw = response.read(262145)
    doc = json.loads(raw)
    if len(raw) > 262144 or doc["year"] != year or not doc.get("papers") or not doc.get("days"):
        raise ValueError(f"Unpublished or invalid China calendar: {year}")
    (ROOT / f"data/china/{year}.json").write_bytes(raw)
for country, zone in REGIONS.items():
    for subdivision in [None, *holidays.country_holidays(country).subdivisions]:
        for year in YEARS:
            dates = holidays.country_holidays(country, subdiv=subdivision, years=year, language="en_US")
            key = country + (f"-{subdivision}" if subdivision else "")
            doc = {"schema_version": 1, "country": country, "subdivision": subdivision, "year": year,
                   "timezone": zone, "weekdays": [d for d in range(7) if d not in dates.weekend],
                   "source": "vacanza/holidays", "source_url": "https://github.com/vacanza/holidays",
                   "revision": f"holidays-{holidays.__version__}", "status": "calculated",
                   "days": [{"date": str(day), "name": name, "is_off_day": True}
                            for day, name in sorted(dates.items()) if day.year == year]}
            path = ROOT / f"data/{key}/{year}.json"
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(json.dumps(doc, ensure_ascii=False, indent=2)+"\n")
            entries.append((key,year))
text = "// Generated by scripts/update-work-calendars.py.\npub fn bytes(key: &str, year: i32) -> Option<&'static [u8]> { match (key, year) {\n"
for key, year in entries:
    text += f'    ("{key}", {year}) => Some(include_bytes!("../data/{key}/{year}.json")),\n'
text += "    _ => None,\n} }\n"
(ROOT / "src/bundled.rs").write_text(text)
print(f"Updated CN annual notices and {len(entries)} regional snapshots")
